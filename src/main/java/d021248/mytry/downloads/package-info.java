/// Download utilities for various media platforms.
///
/// This package provides tools for downloading and processing content from
/// various online media platforms.
///
/// ## Prerequisites
///
/// The YouTube and Spotify demos wrap external CLI tools that must be installed separately:
/// ```
/// pip install yt-dlp spotdl
/// ```
/// The code will compile without them, but will fail at runtime if the tools are not on `PATH`.
///
/// ## Subpackages
///
/// - `spotify` — Spotify playlist download demonstrations (requires `spotdl`)
/// - `youtube` — YouTube video search and download utilities (requires `yt-dlp`)
///
/// @since 1.0
package d021248.mytry.downloads;
